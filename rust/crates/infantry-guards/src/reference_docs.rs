// ---------------------------------------------------------------- protocol

struct Frame {
    konst: String,
    name: String,
    doc: String,
}

fn frames(src: &str) -> (Vec<Frame>, BTreeSet<String>, BTreeSet<String>) {
    let mut out = Vec::new();
    let mut doc = Vec::new();
    for line in src.lines() {
        let t = line.trim();
        if let Some(d) = t.strip_prefix("///") {
            doc.push(d.trim().to_string());
            continue;
        }
        if let Some(rest) = t.strip_prefix("pub const ") {
            if let Some((konst, lit)) = rest.split_once(": &str = ") {
                if let Some(name) = string_literal(lit) {
                    out.push(Frame { konst: konst.to_string(), name, doc: doc.join(" ") });
                }
            }
        }
        doc.clear();
    }
    let list = |name: &str| -> BTreeSet<String> {
        let start = src.find(&format!("pub const {name}: &[&str] = &[")).unwrap_or_else(|| panic!("{name}"));
        let body = &src[start..];
        let body = &body[body.find("&[").unwrap() + 2..body.find("];").unwrap()];
        body.split(',').map(|w| w.trim().to_string()).filter(|w| !w.is_empty()).collect()
    };
    (out, list("ALL"), list("CORRELATED_REQUESTS"))
}

fn protocol(root: &Path) -> String {
    let src = read(root, "rust/crates/infantry-protocol/src/frames.rs");
    let envelope = read(root, "rust/crates/infantry-protocol/src/envelope.rs");
    let contract = read(root, CONTRACT_MD);
    let (frames, all, correlated) = frames(&src);
    let version = frames.iter().find(|f| f.konst == "REQUEST_ID_CONTRACT").map(|f| f.name.clone()).unwrap_or_default();

    // CONTRACT.md sections: (heading, body), newest first as the file keeps them.
    let mut sections: Vec<(String, String)> = Vec::new();
    for line in contract.lines() {
        if line.starts_with('#') {
            sections.push((line.trim_start_matches('#').trim().to_string(), String::new()));
        } else if let Some(last) = sections.last_mut() {
            last.1.push_str(line);
            last.1.push('\n');
        }
    }

    let mut s = String::from(BANNER);
    s.push_str("# Wire protocol reference\n\n");
    s.push_str("Clients (the desktop app, the Android app, the CLI, `infantry mcp serve`) talk to the daemon over one WebSocket,\n");
    s.push_str("`ws://<host>:<port>/ws`, authenticated with the daemon token. Every message is one JSON **envelope**:\n\n");
    let env_struct = envelope.find("pub struct Envelope").map(|i| &envelope[i..]).unwrap_or("");
    let env_struct = &env_struct[..env_struct.find("\n}").map_or(0, |e| e + 2)];
    s.push_str(&format!("```rust\n{}\n```\n\n", env_struct.trim()));
    s.push_str("`type` is a frame name from the table below; `data` is the frame's payload, a JSON text. A request may carry a\n");
    s.push_str(&format!("`requestId` (contract {version}); the answer to a correlated request (marked below) then comes back to that client only.\n\n"));
    s.push_str(&format!(
        "The full history of every frame and field, with the version that added it, is the wire contract text\n`{CONTRACT_MD}` in the repository. The protocol crate's test `contract_md_and_constants_agree` keeps it complete.\n\n"
    ));
    s.push_str(&format!("## Core frames ({})\n\nFrom `rust/crates/infantry-protocol/src/frames.rs`. *Contract sections* counts the sections of CONTRACT.md that\nname the frame and gives the newest one.\n\n", all.len()));
    s.push_str("| Frame | Constant | Correlated | What it is | Contract sections |\n|---|---|---|---|---|\n");
    for f in frames.iter().filter(|f| all.contains(&f.konst)) {
        let needle = format!("`{}`", f.name);
        let hits: Vec<&(String, String)> = sections.iter().filter(|(h, b)| h.contains(&needle) || b.contains(&needle)).collect();
        let sec = match hits.first() {
            Some((h, _)) => format!("{}: {}", hits.len(), md_cell(h.split(" (").next().unwrap_or(h))),
            None => "0".into(),
        };
        s.push_str(&format!(
            "| `{}` | `{}` | {} | {} | {} |\n",
            f.name,
            f.konst,
            if correlated.contains(&f.konst) { "yes" } else { "" },
            md_cell(&f.doc),
            sec
        ));
    }
    s.push_str("\n## Plugin frames\n\nFrames an official plugin serves (`module.json` `daemon.frames`); owner frames (`daemon.ownerFrames`) are\nrefused to agent sessions.\n\n");
    s.push_str("| Plugin | Frame | Kind | Action | Owner only |\n|---|---|---|---|---|\n");
    for (name, m) in official_manifests(root) {
        let owner: BTreeSet<String> = m["daemon"]["ownerFrames"].as_array().map(|a| a.iter().map(prim).collect()).unwrap_or_default();
        for f in m["daemon"]["frames"].as_array().cloned().unwrap_or_default() {
            let (ty, kind, action) = if f.is_string() { (prim(&f), String::new(), String::new()) } else { (prim(&f["type"]), prim(&f["kind"]), prim(&f["action"])) };
            s.push_str(&format!("| {name} | `{ty}` | {kind} | `{action}` | {} |\n", if owner.contains(&ty) { "yes" } else { "" }));
        }
        for o in &owner {
            if !m["daemon"]["frames"].as_array().is_some_and(|a| a.iter().any(|f| prim(&f["type"]) == *o || prim(f) == *o)) {
                s.push_str(&format!("| {name} | `{o}` |  |  | yes |\n"));
            }
        }
    }
    s
}

