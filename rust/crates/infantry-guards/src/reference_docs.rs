/// The namespaces whose dotted string literals in the Rust code are setting keys.
const SETTING_NAMESPACES: &[&str] = &["limits.", "scripting.", "cards.", "triggers.", "knowledge.", "usage.", "sites."];
/// Words on the line (or the doc comment above it) that mark a literal as a setting read, not an event or a file name.
const SETTING_MARKS: &[&str] = &["setting", "Setting", "KEY", "Limit", "LimitDef", "default", "key:", ".get("];

fn settings(root: &Path) -> String {
    let mut s = String::from(BANNER);
    s.push_str("# Settings reference\n\n");
    s.push_str("Settings are keys with a value at one of four scopes: `app`, `project`, `role`, `session` (the narrowest set scope wins).\n");
    s.push_str("Read and change them with `infantry settings get|set|explain <key>`, the MCP tools `infantry_settings_get` /\n");
    s.push_str("`infantry_settings_set`, or the Settings tab. A key left unset uses its default.\n\n");

    s.push_str("## Plugin settings\n\nDeclared by the official plugins (`module.json` `daemon.config`); the Settings tab shows them under the group named.\n\n");
    s.push_str("| Key | Type | Default | Scope | Plugin / group | What it does |\n|---|---|---|---|---|---|\n");
    let mut declared = BTreeSet::new();
    for (name, m) in official_manifests(root) {
        for node in m["daemon"]["config"].as_array().cloned().unwrap_or_default() {
            for f in node["fields"].as_array().cloned().unwrap_or_default() {
                let key = prim(&f["key"]);
                declared.insert(key.clone());
                let what = [prim(&f["label"]), prim(&f["description"])].into_iter().filter(|x| !x.is_empty()).collect::<Vec<_>>().join(". ");
                s.push_str(&format!(
                    "| `{key}` | {} | `{}` | {} | {name} / {} | {} |\n",
                    prim(&f["type"]),
                    md_cell(&prim(&f["default"])),
                    prim(&f["scope"]),
                    md_cell(&prim(&node["group"])),
                    md_cell(&what)
                ));
            }
        }
    }

    // Code-read keys: key -> (default, places).
    let mut found: BTreeMap<String, (String, BTreeSet<String>)> = BTreeMap::new();
    let mut files = Vec::new();
    rs_files(&root.join("rust/crates"), &mut files);
    rs_files(&root.join("rust/plugins"), &mut files);
    for f in &files {
        let r = rel(root, f);
        if r.contains("infantry-guards") {
            continue;
        }
        let src = fs::read_to_string(f).unwrap_or_default().replace("\r\n", "\n");
        let lines: Vec<&str> = non_test(&src).lines().collect();
        for (i, line) in lines.iter().enumerate() {
            let prev = if i > 0 { lines[i - 1] } else { "" };
            let context = format!("{prev}\n{line}");
            if !SETTING_MARKS.iter().any(|m| context.contains(m)) || line.trim_start().starts_with("//") && !line.contains('`') {
                continue;
            }
            for (j, part) in line.split('"').enumerate() {
                if j % 2 == 0 || !SETTING_NAMESPACES.iter().any(|n| part.starts_with(n)) {
                    continue;
                }
                if part.contains(' ') || part.contains('*') || part.ends_with('.') || part.split('.').count() < 2 || part.split('.').any(str::is_empty) {
                    continue;
                }
                let default = default_on_line(line, part).or_else(|| default_on_line(lines.get(i + 1).unwrap_or(&""), "")).unwrap_or_default();
                let e = found.entry(part.to_string()).or_default();
                if e.0.is_empty() {
                    e.0 = default;
                }
                e.1.insert(r.clone());
            }
        }
        // `/// \`key\` default.` above a const.
        for (i, line) in lines.iter().enumerate() {
            let t = line.trim();
            if let Some(rest) = t.strip_prefix("/// `") {
                if let Some((key, tail)) = rest.split_once('`') {
                    if tail.trim_start().starts_with("default") && !key.contains('*') && SETTING_NAMESPACES.iter().any(|n| key.starts_with(n)) {
                        let d = lines.get(i + 1).and_then(|l| l.split_once('=')).map(|(_, v)| v.trim().trim_end_matches(';').to_string()).unwrap_or_default();
                        let e = found.entry(key.to_string()).or_default();
                        if e.0.is_empty() {
                            e.0 = d;
                        }
                        e.1.insert(r.clone());
                    }
                }
            }
        }
    }
    s.push_str("\n## Settings the core reads\n\nKeys the daemon, the CLI and the core crates read, found in the Rust source. *Default* is the value the code\nuses when the key is unset, where it sits next to the key; otherwise read the code at *Read in*.\n\n");
    s.push_str("| Key | Default | Read in |\n|---|---|---|\n");
    for (k, (d, places)) in &found {
        if declared.contains(k) {
            continue;
        }
        let places = places.iter().map(|p| format!("`{p}`")).collect::<Vec<_>>().join(", ");
        s.push_str(&format!("| `{k}` | {} | {places} |\n", if d.is_empty() { String::new() } else { format!("`{}`", md_cell(d)) }));
    }
    s
}

/// A default written beside the key: `default: N` in a struct literal, or `("key", N)` in a tuple.
fn default_on_line(line: &str, key: &str) -> Option<String> {
    if let Some(i) = line.find("default: ") {
        let v: String = line[i + 9..].chars().take_while(|c| !matches!(c, ',' | '}' | ';')).collect();
        return Some(v.trim().to_string()).filter(|v| !v.is_empty() && !v.contains(' '));
    }
    if !key.is_empty() {
        let needle = format!("(\"{key}\", ");
        if let Some(i) = line.find(&needle) {
            let v: String = line[i + needle.len()..].chars().take_while(|c| *c != ')').collect();
            return Some(v.trim().to_string()).filter(|v| !v.is_empty() && !v.contains(' '));
        }
    }
    None
}

