fn cli(root: &Path) -> String {
    let dir = "rust/crates/infantry-cli/src/cli";
    let usage = str_consts(&read(root, &format!("{dir}/usage.rs")), |n| n == "USAGE").remove(0).1;
    let mut s = String::from(BANNER);
    s.push_str("# Command line reference\n\n");
    s.push_str("The `infantry` binary (crate `infantry-cli`). It talks to the daemon over the WebSocket; the connection comes from\n");
    s.push_str("`--url`, `--endpoint` or the `INFANTRY_URL` / `INFANTRY_TOKEN` environment of an agent session. `infantry --help` prints\n");
    s.push_str("the overview below; a wrong command prints its own usage line and exits with code 2.\n\n");

    let mut names = BTreeSet::new();
    let mut files = Vec::new();
    rs_files(&root.join(dir), &mut files);
    for f in &files {
        let src = fs::read_to_string(f).unwrap_or_default();
        for (i, _) in non_test(&src).match_indices("Command { name: \"") {
            let rest = &src[i + 17..];
            names.insert(rest[..rest.find('"').unwrap_or(0)].to_string());
        }
    }
    s.push_str("## Native commands\n\n");
    s.push_str("These commands are served by the binary itself (`registry.rs`); `progress`, `run` and `waiting` also take raw words.\n\n");
    s.push_str(&names.iter().map(|n| format!("`{n}`")).collect::<Vec<_>>().join(", "));
    s.push_str("\n\n## Overview (`infantry --help`)\n\n```text\n");
    s.push_str(usage.trim_end());
    s.push_str("\n```\n\n## Usage lines per command\n\n");
    s.push_str("The usage a command prints when its words are wrong.\n\n");
    for f in &files {
        let src = fs::read_to_string(f).unwrap_or_default().replace("\r\n", "\n");
        let file = f.file_name().unwrap().to_string_lossy().to_string();
        if file == "usage.rs" {
            continue;
        }
        for (name, text) in str_consts(non_test(&src), |n| n.ends_with("USAGE")) {
            s.push_str(&format!("### {} (`{}`)\n\n```text\n{}\n```\n\n", file.trim_end_matches(".rs"), name, text.trim_end()));
        }
    }

    let args = read(root, &format!("{dir}/args.rs"));
    let table = &args[args.find("const FLAGS:").expect("FLAGS")..];
    let table = &table[..table.find("];").expect("FLAGS end")];
    s.push_str("## Flags\n\nOne flag table serves every command; a flag may stand anywhere on the line. Kinds: `value` (must not start\n");
    s.push_str("with `-`), `any` (any next word), `multi` / `multi-any` (repeatable), `switch` (no value).\n\n");
    s.push_str("| Flag | Kind | When its value is missing |\n|---|---|---|\n");
    for line in table.lines() {
        let line = line.trim();
        if !line.starts_with("(\"--") {
            continue;
        }
        let flag = string_literal(&line[1..]).unwrap_or_default();
        let kind = line.split("Kind::").nth(1).map(|k| k.split(',').next().unwrap_or("").trim()).unwrap_or("");
        let kind = match kind {
            "Value" => "value",
            "Any" => "any",
            "Multi" => "multi",
            "MultiAny" => "multi-any",
            _ => "switch",
        };
        let msg_at = line.rfind(", \"").map(|i| &line[i + 2..]).unwrap_or("\"\"");
        let msg = string_literal(msg_at).unwrap_or_default();
        s.push_str(&format!("| `{flag}` | {kind} | {} |\n", md_cell(&msg)));
    }
    s
}

