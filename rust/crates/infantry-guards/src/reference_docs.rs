/// The value of a Rust string literal starting at `s` (`"..."`, `r"..."`, `r#"..."#`), and the bytes it used.
fn string_literal(s: &str) -> Option<String> {
    if let Some(rest) = s.strip_prefix("r#\"") {
        return rest.find("\"#").map(|e| rest[..e].to_string());
    }
    if let Some(rest) = s.strip_prefix("r\"") {
        return rest.find('"').map(|e| rest[..e].to_string());
    }
    let rest = s.strip_prefix('"')?;
    let mut out = String::new();
    let mut it = rest.chars().peekable();
    while let Some(c) = it.next() {
        match c {
            '"' => return Some(out),
            '\\' => match it.next()? {
                'n' => out.push('\n'),
                't' => out.push('\t'),
                'r' => {}
                '0' => out.push('\0'),
                '\n' => {
                    while it.peek().is_some_and(|c| c.is_whitespace()) {
                        it.next();
                    }
                }
                'u' => {
                    let code: String = it.by_ref().skip(1).take_while(|c| *c != '}').collect();
                    out.extend(u32::from_str_radix(&code, 16).ok().and_then(char::from_u32));
                }
                other => out.push(other),
            },
            c => out.push(c),
        }
    }
    None
}

/// Every `const NAME: &str = <literal>;` in `src` whose name passes `want`, in source order.
fn str_consts(src: &str, want: impl Fn(&str) -> bool) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for (i, _) in src.match_indices("const ") {
        let rest = &src[i + 6..];
        let Some(colon) = rest.find(':') else { continue };
        let name = rest[..colon].trim();
        if name.is_empty() || !name.chars().all(|c| c.is_ascii_uppercase() || c == '_' || c.is_ascii_digit()) || !want(name) {
            continue;
        }
        let after = rest[colon + 1..].trim_start();
        let Some(after) = after.strip_prefix("&str") else { continue };
        let Some(after) = after.trim_start().strip_prefix('=') else { continue };
        if let Some(v) = string_literal(after.trim_start()) {
            out.push((name.to_string(), v));
        }
    }
    out
}

/// The `(&str, &str)` pairs of `const NAME: &[(&str, &str)] = &[ ... ];`.
fn str_pairs(src: &str, name: &str) -> Vec<(String, String)> {
    let start = src.find(&format!("const {name}:")).unwrap_or_else(|| panic!("const {name} not found"));
    let body = &src[start..];
    let body = &body[body.find("= &[").expect("array") + 4..];
    let body = &body[..body.find("];").expect("array end")];
    let mut out = Vec::new();
    for line in body.lines() {
        let quoted: Vec<&str> = line.split('"').collect();
        if quoted.len() >= 5 {
            out.push((quoted[1].to_string(), quoted[3].to_string()));
        }
    }
    out
}

/// Source text without its `#[cfg(test)]` part (the test module sits at the end of a file by convention).
fn non_test(src: &str) -> &str {
    src.find("#[cfg(test)]").map_or(src, |i| &src[..i])
}

fn rs_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = fs::read_dir(dir) else { return };
    let mut entries: Vec<PathBuf> = rd.filter_map(|e| e.ok().map(|e| e.path())).collect();
    entries.sort();
    for p in entries {
        let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("");
        if p.is_dir() {
            if !matches!(name, "target" | "tests" | "node_modules" | "benches" | "examples") {
                rs_files(&p, out);
            }
        } else if name.ends_with(".rs") {
            out.push(p);
        }
    }
}

fn rel(root: &Path, p: &Path) -> String {
    p.strip_prefix(root).unwrap_or(p).to_string_lossy().replace('\\', "/")
}

fn md_cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ").trim().to_string()
}

fn official_manifests(root: &Path) -> Vec<(String, Value)> {
    let dir = root.join("rust/plugins/official");
    let mut names: Vec<String> = fs::read_dir(&dir)
        .expect("rust/plugins/official")
        .filter_map(|e| e.ok())
        .filter(|e| e.path().join("module.json").is_file())
        .map(|e| e.file_name().to_string_lossy().to_string())
        .collect();
    names.sort();
    names
        .into_iter()
        .map(|n| {
            let text = read(root, &format!("rust/plugins/official/{n}/module.json"));
            (n.clone(), serde_json::from_str(&text).unwrap_or_else(|e| panic!("{n}/module.json: {e}")))
        })
        .collect()
}

fn prim(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Null => String::new(),
        other => other.to_string(),
    }
}

