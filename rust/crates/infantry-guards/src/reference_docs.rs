fn lua_api(root: &Path) -> String {
    let lua = read(root, "rust/crates/infantry-scripting/src/lua.rs");
    let dispatcher = read(root, "rust/crates/infantry-scripting/src/dispatcher.rs");
    let store = read(root, "rust/crates/infantry-scripting/src/store.rs");
    let tools_cmds = read(root, "rust/crates/infantry-cli/src/cli/tools_cmds.rs");
    let binding = str_consts(&lua, |n| n == "BINDING").remove(0).1;
    let hook_usage = str_consts(&tools_cmds, |n| n == "SCRIPT_USAGE").remove(0).1;

    let mut s = String::from(BANNER);
    s.push_str("# Lua script API reference\n\n");
    s.push_str("Scripts automate the board: a script queues tool calls, the daemon runs them in order as the caller once the\n");
    s.push_str("script ends. Run one with `infantry_script_run` (MCP) or hook it to an event with `infantry script hook add`.\n");
    s.push_str("`infantry_script_api` prints the live version of this page, with every tool the caller may queue (see the\n[MCP tools reference](mcp-tools.md)).\n\n");
    s.push_str("## The `ih` binding\n\nFrom `rust/crates/infantry-scripting/src/lua.rs`.\n\n```text\n");
    s.push_str(binding.trim_end());
    s.push_str("\n```\n\n## Aliases\n\nA short name for a tool: `ih.<alias>{...}`. The built-in aliases are always there; the default table applies while the\nsetting `scripting.aliases` is unset (a stored JSON object replaces it).\n\n");
    s.push_str("| Alias | Tool | Kind |\n|---|---|---|\n");
    for (a, t) in str_pairs(&dispatcher, "BUILTIN_ALIASES") {
        s.push_str(&format!("| `{a}` | `{t}` | built in |\n"));
    }
    for (a, t) in str_pairs(&dispatcher, "DEFAULT_ALIASES") {
        s.push_str(&format!("| `{a}` | `{t}` | default |\n"));
    }
    s.push_str("\n## Hooks\n\n`infantry script` manages scripts and the hooks that run them:\n\n```text\n");
    s.push_str(hook_usage.trim_end());
    s.push_str("\n```\n\n## Bundled scripts\n\nThe starter set every install has (`rust/crates/infantry-scripting/global-scripts/`). Each file's first lines say\nwhat it does and which `input.args` it takes.\n\n");
    s.push_str("| Script | What it does |\n|---|---|\n");
    let start = store.find("pub const BUNDLED").expect("BUNDLED");
    let body = &store[start..];
    let body = &body[..body.find(");").expect("BUNDLED end")];
    for line in body.lines() {
        let Some(file) = line.trim().strip_prefix('"').and_then(|l| l.split('"').next()) else { continue };
        let text = read(root, &format!("rust/crates/infantry-scripting/global-scripts/{file}"));
        let first = text.lines().next().unwrap_or("").trim_start_matches("--").trim();
        let what = first.split_once(": ").map_or(first, |(_, w)| w);
        s.push_str(&format!("| `{file}` | {} |\n", md_cell(what)));
    }
    s
}
