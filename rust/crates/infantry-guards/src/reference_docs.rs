fn schema_args(schema: &Value) -> String {
    let required: Vec<&str> = schema["required"].as_array().map(|a| a.iter().filter_map(Value::as_str).collect()).unwrap_or_default();
    let Some(props) = schema["properties"].as_object() else { return String::new() };
    // Sorted explicitly: feature unification (serde_json preserve_order, enabled by infantry-cli) must not change the page.
    let props: BTreeMap<&String, &Value> = props.iter().collect();
    let mut out = String::new();
    for (k, v) in props {
        let ty = v["type"].as_str().map(str::to_string).unwrap_or_else(|| prim(&v["type"]));
        let ty = if ty.is_empty() { "any".to_string() } else { ty };
        let req = if required.contains(&k.as_str()) { ", required" } else { "" };
        out.push_str(&format!("- `{k}` ({ty}{req}): {}\n", v["description"].as_str().unwrap_or("").replace('\n', " ")));
    }
    out
}

fn mcp_tools(root: &Path) -> String {
    let tools: Vec<Value> = serde_json::from_str(&read(root, "rust/crates/infantry-daemon/src/compose/agent_tools.json")).expect("agent_tools.json");
    let mut s = String::from(BANNER);
    s.push_str("# MCP tools reference\n\n");
    s.push_str(MCP_INTRO);
    s.push_str(&format!("## Core tools ({})\n\nFrom `rust/crates/infantry-daemon/src/compose/agent_tools.json`.\n\n", tools.len()));
    for t in &tools {
        let ro = if t["readOnly"].as_bool() == Some(true) { " (read-only)" } else { "" };
        s.push_str(&format!("### `{}`{ro}\n\n{}\n\n", t["name"].as_str().unwrap_or(""), t["description"].as_str().unwrap_or("").trim()));
        let a = schema_args(&t["inputSchema"]);
        if !a.is_empty() {
            s.push_str(&a);
            s.push('\n');
        }
    }
    s.push_str("## Plugin tools\n\nDeclared in each official plugin's `module.json` (`daemon.tools`). The plugin answers the call; its arguments\n");
    s.push_str("are described in the tool's description. `kind` is what the call does (`read` or `write`), `action` the permission it needs.\n\n");
    for (name, m) in official_manifests(root) {
        let Some(list) = m["daemon"]["tools"].as_array() else { continue };
        s.push_str(&format!("### {name}\n\n| Tool | Kind | Action | What it does |\n|---|---|---|---|\n"));
        for t in list {
            s.push_str(&format!(
                "| `{}` | {} | `{}` | {} |\n",
                prim(&t["name"]),
                prim(&t["kind"]),
                prim(&t["action"]),
                md_cell(t["description"].as_str().unwrap_or(""))
            ));
        }
        s.push('\n');
    }
    s.trim_end().to_string() + "\n"
}

