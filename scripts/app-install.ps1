# Junction-free `pnpm install` for app/ (ticket b56f638d).
# Windows RedirectionGuard (Insider 26300+) blocks node.exe from following NTFS junctions, which pnpm's
# default layout is made of. app/pnpm-workspace.yaml therefore sets nodeLinker=hoisted, symlink=false and
# packageImportMethod=copy (no links at all). With symlink=false pnpm no longer links the workspace
# packages, so this script copies packages/* into shell/node_modules/@infantry/ (re-run after editing them).
# Usage: pwsh scripts/app-install.ps1 [-Build]
param([switch]$Build)
$ErrorActionPreference = 'Stop'
$app = Join-Path $PSScriptRoot '..\app' | Resolve-Path
Push-Location $app
try {
  pnpm install --frozen-lockfile
  if ($LASTEXITCODE) { exit $LASTEXITCODE }
  foreach ($p in Get-ChildItem packages -Directory) {
    $name = (Get-Content (Join-Path $p.FullName package.json) -Raw | ConvertFrom-Json).name   # @infantry/client
    $dest = Join-Path 'shell\node_modules' $name
    if (Test-Path $dest) { Remove-Item $dest -Recurse -Force }
    New-Item -ItemType Directory -Force (Split-Path $dest) | Out-Null
    robocopy $p.FullName $dest /E /XD node_modules /NFL /NDL /NJH /NJS /NP | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy $name failed" }
  }
  # packages/client reaches ../../../src/generated by relative path; from the copy that lands in shell/node_modules/src.
  robocopy src\generated shell\node_modules\src\generated /E /NFL /NDL /NJH /NJS /NP | Out-Null
  if ($LASTEXITCODE -ge 8) { throw 'robocopy generated failed' }
  if ($Build) { pnpm build; exit $LASTEXITCODE }
} finally { Pop-Location }

