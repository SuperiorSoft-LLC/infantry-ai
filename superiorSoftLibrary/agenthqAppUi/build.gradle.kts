    .orEmpty().sortedBy { it.name }.map { ":plugins:demo:${it.name}" }
// GAP-AUDIT-1 (d): the generator itself, one function, so testModuleListGenerator runs the very code the build runs.
/** Writes the module list and the compile-time config from the core / official / demo manifests into [base]. */
fun writeModuleList(base: File, core: Set<File>, official: Set<File>, demo: Set<File>, demoOn: Boolean) {
    // name, entry, buildOrder, official
    fun read(files: Set<File>, official: Boolean) = files.mapNotNull { f ->
        @Suppress("UNCHECKED_CAST")
        val m = groovy.json.JsonSlurper().parse(f) as Map<String, Any?>
        val name = m["name"] as String
        check(name == f.parentFile.name) { "${f.path}: name $name is not its folder's" }
        // A daemon-only plugin (a `daemon` block, no UI part such as Infantry_Lua or Infantry_Scripting) has no
        // ModuleSource to compile into the UI, so it is left out of the list; a UI manifest still needs its entry.
        if (m["entry"] == null && m["daemon"] != null) return@mapNotNull null
        val entry = (m["entry"] as? String)?.takeIf { it.isNotBlank() } ?: error("${f.path}: no entry (its ModuleSource)")
        listOf(name, entry, (m["buildOrder"] as? Number)?.toInt() ?: Int.MAX_VALUE, official, m["config"] ?: emptyList<Any>())
    }
    val modules = (read(core, false) + read(official, true))
        .sortedWith(compareBy({ it[2] as Int }, { it[0] as String }))
    // OVERRIDE-1: the demo modules go last, so their overrides and config win over the live ones (D16); desktop never lists them.
    val demoModules = if (demoOn) read(demo, true).sortedBy { it[0] as String } else emptyList()
    val compiledIn = modules + demoModules
    val pkg = "package com.superiorsoftllc.agenthq.plugins.core"
    val header = "// GENERATED by :superiorSoftLibrary:agenthqAppUi:generateModuleList from plugins/core/*/module.json and plugins/official/*/module.json. Do not edit."
    val common = buildString {
        appendLine(header)
        appendLine(pkg)
        appendLine()
        appendLine("import com.superiorsoftllc.agenthq.ui.plugin.AgentHqModule")
        appendLine("import com.superiorsoftllc.agenthq.ui.plugin.ModuleSource")
        appendLine("import com.superiorsoftllc.agenthq.ui.plugin.TabFactory")
        appendLine()
        appendLine("/** RUNTIME-1: the modules compiled into this build, one [ModuleSource] per module, in `buildOrder`. */")
        appendLine("object CoreModules {")
        appendLine("    val sources: List<ModuleSource> = compiledModuleSources()")
        appendLine()
        appendLine("    val all: List<AgentHqModule> = sources.flatMap { it.modules() }")
        appendLine()
        appendLine("    val factory: TabFactory by lazy { TabFactory(all) }")
        appendLine("}")
        appendLine()
        appendLine("/** RUNTIME-3: the core modules, plus the official ones where they are compiled in (web, Android; not desktop). */")
        appendLine("internal expect fun compiledModuleSources(): List<ModuleSource>")
        appendLine()
        appendLine("/** S4: hands [CoreModules] to the shell (`META-INF/services/com.superiorsoftllc.agenthq.ui.plugin.ModuleSource`) (empty on desktop since RUNTIME-26). */")
        appendLine("class CoreModuleSource : ModuleSource {")
        appendLine("    override fun modules(): List<AgentHqModule> = CoreModules.all")
        appendLine("}")
    }
    fun actual(list: List<List<Any>>, doc: String, withConfig: Boolean = false) = buildString {
        appendLine(header)
        appendLine(pkg)
        appendLine()
        appendLine("import com.superiorsoftllc.agenthq.ui.plugin.ModuleSource")
        appendLine()
        appendLine("/** $doc */")
        appendLine("internal actual fun compiledModuleSources(): List<ModuleSource> {")
        if (withConfig) appendLine("    GeneratedConfig.install()")
        appendLine("    return listOf(")
        list.forEach { appendLine("        ${it[1]}(), // ${it[0]}${if (it[3] == true) " (official)" else ""}") }
        appendLine("    )")
        appendLine("}")
    }
    // CONFIG-9: web and Android compile the module `config` in: GeneratedConfig.JSON = each module's config, in load order.
    fun generatedConfig(list: List<List<Any>>, platform: String): String {
        val json = list.filter { (it[4] as? List<*>)?.isNotEmpty() == true }
            .joinToString(",", "[", "]") { """{"module":${groovy.json.JsonOutput.toJson(it[0])},"config":${groovy.json.JsonOutput.toJson(it[4])}}""" }
        // the text must equal the concatenation of the modules' config (module order, nothing dropped)
        val expected = list.filter { (it[4] as? List<*>)?.isNotEmpty() == true }.map { mapOf("module" to it[0], "config" to it[4]) }
        check(groovy.json.JsonSlurper().parseText(json) == expected) { "GeneratedConfig.JSON is not the concatenation of the modules' config" }
        val chunks = json.chunked(8000).joinToString(",\n        ") { "\"\"\"" + it.replace("$", "\${'$'}") + "\"\"\"" }
        return buildString {
            appendLine(header)
            appendLine(pkg)
            appendLine()
            appendLine("import com.superiorsoftllc.agenthq.ui.plugin.config.CompiledConfig")
            appendLine()
            appendLine("/** CONFIG-9: the compile-time config of the $platform build (docs/CONFIG-MANIFEST-DESIGN.md section 7). */")
            appendLine("internal object GeneratedConfig {")
            appendLine("    const val PLATFORM: String = \"$platform\"")
            appendLine("    val JSON: String = listOf(")
            appendLine("        $chunks")
            appendLine("    ).joinToString(\"\")")
            appendLine()
            appendLine("    fun install() = CompiledConfig.install(JSON, PLATFORM)")
            appendLine("}")
        }
    }
    base.deleteRecursively()
    fun write(dir: String, file: String, text: String) =
        File(base, "$dir/kotlin/com/superiorsoftllc/agenthq/plugins/core").apply { mkdirs() }.resolve(file).writeText(text)
    write("commonMain", "CoreModules.kt", common)
    write("jvmMain", "CoreModules.jvm.kt", actual(modules.filter { it[3] != true }, "RUNTIME-3: desktop: core only; the official modules load at run time from their signed jars."))
    write("compiledIn", "CoreModules.compiledIn.kt", actual(compiledIn, "RUNTIME-3: web and Android: core and official, compiled in (D9).", withConfig = true))
    write("generatedConfigWeb", "GeneratedConfig.kt", generatedConfig(compiledIn, "web"))
    write("generatedConfigAndroid", "GeneratedConfig.kt", generatedConfig(compiledIn, "android"))
}

val generateModuleList = tasks.register("generateModuleList") {
    group = "build"
    description = "Writes CoreModules.kt from plugins/core/*/module.json and plugins/official/*/module.json (entry + buildOrder)."
    val manifests = rootProject.fileTree("plugins/core") { include("*/module.json"); exclude("_*/**") }
    val officialManifests = rootProject.fileTree("plugins/official") { include("*/module.json"); exclude("_*/**") }
    inputs.files(manifests).withPropertyName("manifests")
    inputs.files(officialManifests).withPropertyName("officialManifests")
    val demoManifests = rootProject.fileTree("plugins/demo") { include("*/module.json"); exclude("_*/**") }
    inputs.files(demoManifests).withPropertyName("demoManifests")
    inputs.property("demo", demoBuild)
    val root = generatedModuleListRoot
    outputs.dir(root)
    doLast { writeModuleList(root.get().asFile, manifests.files, officialManifests.files, demoManifests.files, demoBuild) }
}

// GAP-AUDIT-1 (d): the -Pdemo flag, tested both ways on every jvmTest / check (no manual run): generated into two temp
// folders from the real manifests, the demo-off list must name no demo module, and the demo-on list must be the live
// list with exactly the demo modules appended last (desktop list and common file byte-identical; config = live + demo).
val testModuleListGenerator = tasks.register("testModuleListGenerator") {
    group = "verification"
    description = "Generates the module list with -Pdemo off and on and checks the difference is exactly the demo modules, last."
    val core = rootProject.fileTree("plugins/core") { include("*/module.json"); exclude("_*/**") }
    val official = rootProject.fileTree("plugins/official") { include("*/module.json"); exclude("_*/**") }
    val demo = rootProject.fileTree("plugins/demo") { include("*/module.json"); exclude("_*/**") }
    inputs.files(core, official, demo)
    val out = layout.buildDirectory.dir("tmp/testModuleListGenerator")
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.apply { deleteRecursively() }
        val off = File(dir, "off"); val on = File(dir, "on"); val again = File(dir, "again")
        writeModuleList(off, core.files, official.files, demo.files, demoOn = false)
        writeModuleList(on, core.files, official.files, demo.files, demoOn = true)
        writeModuleList(again, core.files, official.files, demo.files, demoOn = false)
        val pkg = "kotlin/com/superiorsoftllc/agenthq/plugins/core"
        fun text(root: File, set: String, file: String) = File(root, "$set/$pkg/$file").readText()
        fun entries(root: File) = text(root, "compiledIn", "CoreModules.compiledIn.kt").lines().filter { it.contains("(), // ") }
        @Suppress("UNCHECKED_CAST")
        val demoNames = demo.files.map { (groovy.json.JsonSlurper().parse(it) as Map<String, Any?>)["name"] as String }.sorted()
        check(demoNames.isNotEmpty()) { "no demo module under plugins/demo: nothing to test" }
        val offList = entries(off); val onList = entries(on)
        check(demoNames.none { n -> offList.any { it.contains("// $n") } }) { "demo off lists a demo module: $offList" }
        check(onList.take(offList.size) == offList) { "demo on does not keep the live list first, in order: $offList / $onList" }
        check(onList.drop(offList.size).map { it.substringAfter("// ").substringBefore(" ") } == demoNames) { "demo on must append exactly $demoNames, got ${onList.drop(offList.size)}" }
        for ((set, file) in listOf("jvmMain" to "CoreModules.jvm.kt", "commonMain" to "CoreModules.kt")) {
            check(text(off, set, file) == text(on, set, file)) { "$set/$file differs with -Pdemo: the desktop never lists demo modules" }
        }
        for (set in listOf("compiledIn", "jvmMain", "commonMain", "generatedConfigWeb", "generatedConfigAndroid")) {
            File(off, set).walkTopDown().filter { it.isFile }.forEach { f ->
                check(f.readText() == File(again, f.relativeTo(off).path).readText()) { "${f.name}: two runs differ (not deterministic)" }
            }
        }
        fun config(root: File, set: String): List<Any?> {
            val t = text(root, set, "GeneratedConfig.kt")
            val json = Regex("\"\"\"(.*?)\"\"\"", RegexOption.DOT_MATCHES_ALL).findAll(t).joinToString("") { it.groupValues[1].replace("\${'$'}", "$") }
            return groovy.json.JsonSlurper().parseText(json) as List<Any?>
        }
        for (set in listOf("generatedConfigWeb", "generatedConfigAndroid")) {
            val offCfg = config(off, set); val onCfg = config(on, set)
            check(onCfg.take(offCfg.size) == offCfg) { "$set: demo on changes the live modules' config" }
            @Suppress("UNCHECKED_CAST")
            val added = onCfg.drop(offCfg.size).map { (it as Map<String, Any?>)["module"] as String }
            check(added.all { it in demoNames }) { "$set: demo on adds config of non-demo modules: $added" }
        }
        println("testModuleListGenerator: live ${offList.size} modules; -Pdemo=true appends $demoNames; desktop list unchanged")
    }
}
tasks.matching { it.name == "jvmTest" || it.name == "check" }.configureEach { dependsOn(testModuleListGenerator) }

