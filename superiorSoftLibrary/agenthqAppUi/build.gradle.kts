// RUNTIME-1 (docs/RUNTIME-PLUGINS-AUDIT.md section 3, step 1): the module list, GENERATED from plugins/core/*/module.json.
// Each module.json names its own ModuleSource (`entry`) and its place in the list (`buildOrder`, then name). The output,
// object CoreModules { all; factory } and the bundle entry CoreModuleSource, is the one packaging list of every build:
// desktop (ServiceLoader -> CoreModuleSource), web (agentHqWeb Main.kt) and Android. Add a core module by adding its folder.
// RUNTIME-3: plus plugins/official/*/module.json, compiled in on web and Android only (D9: they cannot load a jar at run
// time); the desktop list leaves them out and loads their signed jars from official/ at run time. So the list is one
// expect (commonMain) with two actuals: jvmMain (core only) and compiledIn (core + official, for wasmJs and android).
val generatedModuleListRoot = layout.buildDirectory.dir("generated/moduleList")
val generatedModuleListDir = generatedModuleListRoot.map { it.dir("commonMain/kotlin") }
val generatedJvmListDir = generatedModuleListRoot.map { it.dir("jvmMain/kotlin") }
val generatedCompiledInListDir = generatedModuleListRoot.map { it.dir("compiledIn/kotlin") }
// RUNTIME-3: the official modules that have sources (their own projects; settings.gradle.kts scans the same folder).
val officialModuleProjects = rootProject.file("plugins/official").listFiles { f -> f.isDirectory && !f.name.startsWith("_") && File(f, "build.gradle.kts").isFile }
    .orEmpty().sortedBy { it.name }.map { ":plugins:official:${it.name}" }
val generateModuleList = tasks.register("generateModuleList") {
    group = "build"
    description = "Writes CoreModules.kt from plugins/core/*/module.json and plugins/official/*/module.json (entry + buildOrder)."
    val manifests = rootProject.fileTree("plugins/core") { include("Infantry_*/module.json") }
    val officialManifests = rootProject.fileTree("plugins/official") { include("Infantry_*/module.json") }
    inputs.files(manifests).withPropertyName("manifests")
    inputs.files(officialManifests).withPropertyName("officialManifests")
    val root = generatedModuleListRoot
    outputs.dir(root)
    doLast {
        // name, entry, buildOrder, official
        fun read(files: Set<File>, official: Boolean) = files.map { f ->
            @Suppress("UNCHECKED_CAST")
            val m = groovy.json.JsonSlurper().parse(f) as Map<String, Any?>
            val name = m["name"] as String
            check(name == f.parentFile.name) { "${f.path}: name $name is not its folder's" }
            val entry = (m["entry"] as? String)?.takeIf { it.isNotBlank() } ?: error("${f.path}: no entry (its ModuleSource)")
            listOf(name, entry, (m["buildOrder"] as? Number)?.toInt() ?: Int.MAX_VALUE, official)
        }
        val modules = (read(manifests.files, false) + read(officialManifests.files, true))
            .sortedWith(compareBy({ it[2] as Int }, { it[0] as String }))
        val pkg = "package com.superiorsoftllc.agenthq.plugins.core"
        val header = "// GENERATED by :superiorSoftLibrary:agenthqAppUi:generateModuleList from plugins/core/*/module.json and plugins/official/*/module.json. Do not edit."
        val common = buildString {
            appendLine(header)
            appendLine(pkg)
            appendLine()
            appendLine("import com.superiorsoftllc.agenthq.ui.plugin.AgentHqModule")
            appendLine("import com.superiorsoftllc.agenthq.ui.plugin.ModuleSource")
            appendLine("import com.superiorsoftllc.agenthq.ui.plugin.TabFactory")
            appendLine()
            appendLine("/** RUNTIME-1: the modules compiled into this build, one [ModuleSource] per module, in `buildOrder`. */")
            appendLine("object CoreModules {")
            appendLine("    val sources: List<ModuleSource> = compiledModuleSources()")
            appendLine()
            appendLine("    val all: List<AgentHqModule> = sources.flatMap { it.modules() }")
            appendLine()
            appendLine("    val factory: TabFactory by lazy { TabFactory(all) }")
            appendLine("}")
            appendLine()
            appendLine("/** RUNTIME-3: the core modules, plus the official ones where they are compiled in (web, Android; not desktop). */")
            appendLine("internal expect fun compiledModuleSources(): List<ModuleSource>")
            appendLine()
            appendLine("/** S4: hands [CoreModules] to the shell (`META-INF/services/com.superiorsoftllc.agenthq.ui.plugin.ModuleSource`) and is App_UI.ihq's entry. */")
            appendLine("class CoreModuleSource : ModuleSource {")
            appendLine("    override fun modules(): List<AgentHqModule> = CoreModules.all")
            appendLine("}")
        }
        fun actual(list: List<List<Any>>, doc: String) = buildString {
            appendLine(header)
            appendLine(pkg)
            appendLine()
            appendLine("import com.superiorsoftllc.agenthq.ui.plugin.ModuleSource")
            appendLine()
            appendLine("/** $doc */")
            appendLine("internal actual fun compiledModuleSources(): List<ModuleSource> = listOf(")
            list.forEach { appendLine("    ${it[1]}(), // ${it[0]}${if (it[3] == true) " (official)" else ""}") }
            appendLine(")")
        }
        val base = root.get().asFile
        base.deleteRecursively()
        fun write(dir: String, file: String, text: String) =
            File(base, "$dir/kotlin/com/superiorsoftllc/agenthq/plugins/core").apply { mkdirs() }.resolve(file).writeText(text)
        write("commonMain", "CoreModules.kt", common)
        write("jvmMain", "CoreModules.jvm.kt", actual(modules.filter { it[3] != true }, "RUNTIME-3: desktop: core only; the official modules load at run time from their signed jars."))
        write("compiledIn", "CoreModules.compiledIn.kt", actual(modules, "RUNTIME-3: web and Android: core and official, compiled in (D9)."))
    }
}

kotlin {
    jvmToolchain(21)
    jvm()
    @OptIn(org.jetbrains.kotlin.gradle.ExperimentalWasmDsl::class)
    wasmJs { browser() }
    androidLibrary {
        namespace = "com.superiorsoftllc.agenthq.ui.app"
        compileSdk = 36
        minSdk = 24
    }

    sourceSets {
        // PLUGINS-1: the core modules live in <repo>/plugins/core and are compiled into every target from there.
        // NS2: except Infantry_Board, its own project (plugins/core/Infantry_Board), which this one depends on.
        commonMain {
            // Each module folder is its own srcDir rather than plugins/core with an exclude: the Android compile
            // (compileAndroidMain) ignores the exclude and would compile Infantry_Board's build script, tests and
            // outputs. CoreModules.kt (the module list + CoreModuleSource) is generated: generateModuleList.
            rootProject.file("plugins/core").listFiles().orEmpty()
                .filter { it.isDirectory && it.name.startsWith("Infantry_") && it.name != "Infantry_Board" }
                .sortedBy { it.name }
                .forEach { kotlin.srcDir(it) }
            kotlin.srcDir(generateModuleList.map { generatedModuleListDir.get() })
        }
        jvmMain { kotlin.srcDir(generateModuleList.map { generatedJvmListDir.get() }) }
        // RUNTIME-3: web and Android compile the official modules in (the same sources as the desktop jar).
        wasmJsMain {
            kotlin.srcDir(generateModuleList.map { generatedCompiledInListDir.get() })
            dependencies { officialModuleProjects.forEach { implementation(project(it)) } }
        }
        androidMain {
            kotlin.srcDir(generateModuleList.map { generatedCompiledInListDir.get() })
            dependencies { officialModuleProjects.forEach { implementation(project(it)) } }
        }
        commonMain.dependencies {
            api(project(":superiorSoftLibrary:agenthqUiCore"))
            api(project(":plugins:core:Infantry_Board"))
            implementation(compose.runtime)
            implementation(compose.foundation)
            implementation(compose.material3)
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
        }
    }
}

// S6 (drop-in path): the app UI as one droppable file, build/ihq/App_UI.ihq: module.json (Infantry_AppUi's, with its entry
// the ModuleSource that hands over every core module, so the desktop loads it as a bundle) and lib/App_UI.jar (this
// module's jvm jar). One .ihq, one signature, 19 modules (the bundle). NS2: App_UI.jar also carries Infantry_Board's jar
// contents (appUiBundleJar), so the bundle still holds the board. Without -Pihq.keystore it is unsigned and the installer refuses it.
// The drop-in acceptance (agentHqUi renderTabShotsForDiff -PtabShotsExtra=dropin) signs a copy with a throwaway key.
val appUiIhqDir = layout.buildDirectory.dir("ihq")
val appUiIhqManifest = tasks.register("appUiIhqManifest") {
    val source = rootProject.file("plugins/core/Infantry_AppUi/module.json")
    inputs.file(source)
    val out = appUiIhqDir.map { it.file("stage/module.json") }
    outputs.file(out)
    doLast {
        @Suppress("UNCHECKED_CAST")
        val m = groovy.json.JsonSlurper().parse(source) as MutableMap<String, Any?>
        m["entry"] = "com.superiorsoftllc.agenthq.plugins.core.CoreModuleSource"
        m["jar"] = "lib/App_UI.jar"
        out.get().asFile.also { it.parentFile.mkdirs() }.writeText(groovy.json.JsonOutput.prettyPrint(groovy.json.JsonOutput.toJson(m)) + "\n")
    }
}
// NS2: this module's jvm jar plus Infantry_Board's, merged, so App_UI.jar keeps bundling the board.
val appUiBundleJar = tasks.register<Jar>("appUiBundleJar") {
    val own = tasks.named<Jar>("jvmJar")
    val board = project(":plugins:core:Infantry_Board").tasks.named<Jar>("jvmJar")
    dependsOn(own, board)
    archiveFileName.set("App_UI.jar")
    destinationDirectory.set(appUiIhqDir.map { it.dir("bundle") })
    duplicatesStrategy = DuplicatesStrategy.EXCLUDE
    isPreserveFileTimestamps = false
    isReproducibleFileOrder = true
    from(own.map { zipTree(it.archiveFile) })
    from(board.map { zipTree(it.archiveFile) })
}
tasks.register<Zip>("appUiIhq") {
    group = "build"
    description = "Packages the app UI into build/ihq/App_UI.ihq (signed if -Pihq.keystore is given, else unsigned)."
    val jar = appUiBundleJar
    dependsOn(appUiIhqManifest, jar)
    archiveFileName.set("App_UI.ihq")
    destinationDirectory.set(appUiIhqDir)
    isPreserveFileTimestamps = false
    isReproducibleFileOrder = true
    from(appUiIhqManifest.map { appUiIhqDir.get().file("stage/module.json") })
    from(jar.map { it.archiveFile }) { into("lib"); rename { "App_UI.jar" } }
    // S7: signed with the Infantry key when -Pihq.keystore / -Pihq.alias are given (password in env IHQ_STOREPASS), as
    // gradle/ihq.gradle.kts does for a plugin. The one signature covers the bundle's jar and its module.json, so the
    // installer reads the whole 18-module app UI as core tier from the signer. The key itself is never in the repo.
    val keystore = providers.gradleProperty("ihq.keystore")
    val alias = providers.gradleProperty("ihq.alias")
    val storePass = providers.environmentVariable("IHQ_STOREPASS")
    doLast {
        if (keystore.isPresent) {
            val file = archiveFile.get().asFile
            val jarsigner = File(File(System.getProperty("java.home"), "bin"), "jarsigner" + if (org.gradle.internal.os.OperatingSystem.current().isWindows) ".exe" else "").path
            val p = ProcessBuilder(jarsigner, "-keystore", keystore.get(), "-storepass", storePass.orNull ?: error("IHQ_STOREPASS is not set"), file.path, alias.orNull ?: error("-Pihq.alias is required")).redirectErrorStream(true).start()
            val text = p.inputStream.bufferedReader().readText()
            check(p.waitFor() == 0) { "jarsigner failed: $text" }
        }
    }
}
