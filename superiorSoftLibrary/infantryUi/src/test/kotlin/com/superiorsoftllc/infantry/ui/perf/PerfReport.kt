package com.superiorsoftllc.infantry.ui.perf

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonPrimitive
import java.io.File
import java.time.LocalDate
import java.time.LocalDateTime
import java.time.format.DateTimeFormatter
import kotlin.math.abs

/**
 * PERF-1: one JSON per run under `docs/perf/runs/`, and `docs/perf/infantry-profile-<date>.md` rebuilt from every run of
 * that date. Anything below [NOTES_MARKER] in an existing report is hand-written analysis and is kept verbatim.
 */
object PerfReport {
    const val NOTES_MARKER = "<!-- PERF-1 notes: everything below this line is hand-written and kept when the report is regenerated -->"

    /** Spread allowed between runs (acceptance 1). */
    const val TOLERANCE = 0.15

    /** Idle CPU is a few tenths of a percent; a relative spread on it is noise, so it is held to an absolute band. */
    const val CPU_ABS_TOLERANCE = 0.5

    fun writeRun(docsDir: File, started: LocalDateTime, values: Map<String, Any?>): File {
        val dir = File(docsDir, "runs").apply { mkdirs() }
        val name = "infantry-profile-${started.format(DateTimeFormatter.ofPattern("yyyy-MM-dd-HHmmss"))}.json"
        val json = JsonObject(values.mapValues { (_, v) ->
            when (v) {
                null -> JsonPrimitive(null as String?)
                is Number -> JsonPrimitive(v)
                is Boolean -> JsonPrimitive(v)
                else -> JsonPrimitive(v.toString())
            }
        })
        return File(dir, name).apply { writeText(Json { prettyPrint = true }.encodeToString(JsonObject.serializer(), json) + "\n") }
    }

    class Run(val file: File, private val v: Map<String, String?>) {
        operator fun get(key: String): String? = v[key]
        fun num(key: String): Double? = v[key]?.toDoubleOrNull()
        val keys: Set<String> get() = v.keys
        val label: String get() = v["startedAt"]?.substringAfter('T')?.take(8) ?: file.nameWithoutExtension
    }

    fun runsOf(docsDir: File, date: LocalDate): List<Run> =
        File(docsDir, "runs").listFiles { f -> f.name.startsWith("infantry-profile-$date-") && f.extension == "json" }.orEmpty()
            .sortedBy { it.name }
            .map { f ->
                val o = Json.parseToJsonElement(f.readText()) as JsonObject
                Run(f, o.mapValues { (_, e) -> runCatching { e.jsonPrimitive.contentOrNull }.getOrNull() })
            }

    /** Relative spread (max-min)/mean; null when fewer than two values. */
    fun spread(values: List<Double>): Double? {
        if (values.size < 2) return null
        val mean = values.average()
        if (mean == 0.0) return 0.0
        return (values.max() - values.min()) / mean
    }

    fun writeDoc(docsDir: File, date: LocalDate): File {
        val runs = runsOf(docsDir, date)
        val doc = File(docsDir, "infantry-profile-$date.md")
        val kept = doc.takeIf { it.isFile }?.readText()?.substringAfter(NOTES_MARKER, missingDelimiterValue = "")?.trimStart('\n', '\r').orEmpty()
        doc.writeText(render(date, runs) + "\n" + NOTES_MARKER + "\n\n" + kept.ifBlank { "_No analysis written yet._\n" })
        return doc
    }

    private fun f0(d: Double?) = d?.let { "%.0f".format(it) } ?: "n/a"
    private fun f2(d: Double?) = d?.let { "%.2f".format(it) } ?: "n/a"
    private fun sum(a: Double?, b: Double?) = if (a == null || b == null) null else a + b

    fun render(date: LocalDate, runs: List<Run>): String = buildString {
        val last = runs.lastOrNull() ?: return "# Infantry profile $date\n\nNo runs.\n"
        val idleMin = last["config.idleMinutes"]
        appendLine("# Infantry profile, $date")
        appendLine()
        appendLine("Generated by `./gradlew :superiorSoftLibrary:infantry:perfProfile` (PERF-1). Measurement only: nothing was tuned.")
        appendLine("Runs on this date: ${runs.size} (${runs.joinToString { it.file.name }}, in `docs/perf/runs/`).")
        appendLine()
        appendLine("## What was measured")
        appendLine()
        appendLine("- **Daemon JVM**: `DaemonMainKt` on infantry's `installDist` classpath, as `runDaemon` runs it. READY = its `listening on ws://...` line.")
        appendLine("- **UI JVM**: `MainKt` (the dev desktop window, Compose/Skia) on infantryUi's main runtime classpath, as `run` runs it, pointed at the daemon by `INFANTRY_WS_URL`. READY = the daemon logs the window's `ws connected`.")
        appendLine("- **Startup** is the median of ${last["config.startupTrials"]} cold JVM starts per process (each trial daemon on its own fresh temp state dir; each trial window closed after READY); the last start of each is the one measured below.")
        appendLine("- Both in a fresh temp INFANTRY home (`INFANTRY_STATE_DIR`, `INFANTRY_HOME`, `-Duser.home`), on a free port, with the JVM flags in the Daemon/UI command rows below (PERF-2: the shipped caps from `infantry/jvm-caps.txt`; runs before PERF-2 used heap defaults, no `-Xmx`).")
        appendLine("- **Idle**: ${last["config.settleSeconds"]} s after both are READY. **Load**: ${last["config.agents"]} stub-harness agents (started by a separate driver client), each streaming ${last["config.lines"]} text lines of ~140 chars (${last["config.paceMs"]} ms apart); \"peak\" is the highest working set sampled every 1 s during the stream, the snapshot is taken 15 s after the last agent finished. **After idle**: $idleMin min with no client but the window. **After full GC**: `jcmd GC.run` on both, then 5 s.")
        appendLine("- **Idle CPU**: `ProcessHandle.totalCpuDuration` over ${last["config.cpuSeconds"]} s, in % of ONE core (100 = one core fully busy).")
        appendLine("- Memory: Working Set (`Get-Process WorkingSet64`, the number Task Manager shows by default) and Private Bytes; heap from `jcmd GC.heap_info` (used / committed).")
        appendLine()
        appendLine("## Machine and JVM")
        appendLine()
        appendLine("| | |")
        appendLine("|---|---|")
        appendLine("| OS | ${last["machine.os"]} |")
        appendLine("| CPU | ${last["machine.cpu"]} (${last["machine.cores"]} logical cores) |")
        appendLine("| RAM | ${last["machine.ramGb"]} GB (free at start of the last run: ${last["machine.freeRamGbAtStart"]} GB) |")
        appendLine("| Daemon JVM | ${last["daemon.vmVersion"]} |")
        appendLine("| UI JVM | ${last["ui.vmVersion"]} |")
        appendLine("| Daemon command | `java ${last["daemon.cmdline"]}` |")
        appendLine("| UI command | `java ${last["ui.cmdline"]}` |")
        appendLine("| Daemon final flags | `${last["daemon.flags"]}` |")
        appendLine("| UI final flags | `${last["ui.flags"]}` |")
        appendLine()
        appendLine("`-XX:NativeMemoryTracking=summary` adds a few MB of its own bookkeeping to both JVMs (it is listed in the NMT table). It is on so the cost breakdown below exists; pass `-PperfNmt=false` for a run without it.")
        appendLine()

        runs.forEachIndexed { i, run -> appendRun(i + 1, run) }

        if (runs.size >= 2) appendRepeatability(runs)

        appendNmt(last)
        appendReferenceApp(last)
        appendIsolation(runs)
    }

    private fun StringBuilder.appendRun(n: Int, r: Run) {
        val idleMin = r["config.idleMinutes"]
        fun row(label: String, d: String?, u: String?, both: String?) = appendLine("| $label | ${d ?: "n/a"} | ${u ?: "n/a"} | ${both ?: ""} |")
        fun mem(label: String, key: String) = row(label, f0(r.num("daemon.$key")), f0(r.num("ui.$key")), f0(sum(r.num("daemon.$key"), r.num("ui.$key"))))
        fun heap(label: String, point: String) = row(
            label,
            "${f0(r.num("daemon.$point.heapUsedMb"))} / ${f0(r.num("daemon.$point.heapCommittedMb"))}",
            "${f0(r.num("ui.$point.heapUsedMb"))} / ${f0(r.num("ui.$point.heapCommittedMb"))}",
            null,
        )
        appendLine("## Run $n (${r["startedAt"]})")
        appendLine()
        appendLine("| Metric | Daemon JVM | UI JVM | Daemon + UI |")
        appendLine("|---|---:|---:|---:|")
        row("Startup to READY, median of ${r["config.startupTrials"]} (ms)", r["daemon.startupMs"], r["ui.startupMs"], null)
        row("Startup samples (ms)", r["daemon.startupSamplesMs"], r["ui.startupSamplesMs"], null)
        mem("Working set, idle (MB)", "idle.wsMb")
        mem("Private bytes, idle (MB)", "idle.privateMb")
        heap("Heap used / committed, idle (MB)", "idle")
        mem("Working set, under load, peak (MB)", "loadPeak.wsMb")
        mem("Working set, after load (MB)", "load.wsMb")
        mem("Private bytes, after load (MB)", "load.privateMb")
        heap("Heap used / committed, after load (MB)", "load")
        mem("Working set, after $idleMin min idle (MB)", "afterIdle.wsMb")
        mem("Private bytes, after $idleMin min idle (MB)", "afterIdle.privateMb")
        heap("Heap used / committed, after $idleMin min idle (MB)", "afterIdle")
        mem("Working set, after full GC (MB)", "afterGc.wsMb")
        heap("Heap used (live) / committed, after full GC (MB)", "afterGc")
        row("Idle CPU, before load (% of one core)", f2(r.num("daemon.cpuIdlePct")), f2(r.num("ui.cpuIdlePct")), f2(sum(r.num("daemon.cpuIdlePct"), r.num("ui.cpuIdlePct"))))
        row("Idle CPU, after $idleMin min (% of one core)", f2(r.num("daemon.cpuAfterIdlePct")), f2(r.num("ui.cpuAfterIdlePct")), f2(sum(r.num("daemon.cpuAfterIdlePct"), r.num("ui.cpuAfterIdlePct"))))
        row("Threads, idle / after load", "${r["daemon.idle.threads"]} / ${r["daemon.load.threads"]}", "${r["ui.idle.threads"]} / ${r["ui.load.threads"]}", null)
        appendLine()
        appendLine("Load: ${r["config.agents"]} agents x ${r["config.lines"]} lines streamed in ${r["load.streamMs"]} ms; the driver window ended with ${r["load.driverTranscriptEntries"]} transcript entries.")
        r["notes"]?.takeIf { it.isNotBlank() }?.let { appendLine("Notes: $it") }
        appendLine()
    }

    /** The metrics acceptance 1 holds to the 15% band. */
    private val REPEATED = listOf(
        "daemon.startupMs" to "Daemon startup (ms)",
        "ui.startupMs" to "UI startup (ms)",
        "daemon.idle.wsMb" to "Daemon WS idle (MB)",
        "ui.idle.wsMb" to "UI WS idle (MB)",
        "daemon.load.wsMb" to "Daemon WS after load (MB)",
        "ui.load.wsMb" to "UI WS after load (MB)",
        "daemon.afterIdle.wsMb" to "Daemon WS after idle (MB)",
        "ui.afterIdle.wsMb" to "UI WS after idle (MB)",
        "daemon.afterIdle.heapCommittedMb" to "Daemon heap committed after idle (MB)",
        "ui.afterIdle.heapCommittedMb" to "UI heap committed after idle (MB)",
        "daemon.afterGc.heapUsedMb" to "Daemon live heap after GC (MB)",
        "ui.afterGc.heapUsedMb" to "UI live heap after GC (MB)",
    )
    private val REPEATED_CPU = listOf(
        "daemon.cpuIdlePct" to "Daemon idle CPU (% core)",
        "ui.cpuIdlePct" to "UI idle CPU (% core)",
        "daemon.cpuAfterIdlePct" to "Daemon idle CPU after load (% core)",
        "ui.cpuAfterIdlePct" to "UI idle CPU after load (% core)",
    )

    private fun StringBuilder.appendRepeatability(runs: List<Run>) {
        appendLine("## Repeatability (acceptance 1: within 15%)")
        appendLine()
        appendLine("Spread = (max - min) / mean across the ${runs.size} runs. Idle CPU is a fraction of a percent, so it is held to an absolute band of ${CPU_ABS_TOLERANCE} percentage points instead.")
        appendLine()
        appendLine("| Metric | " + runs.joinToString(" | ") { it.label } + " | Spread | Within? |")
        appendLine("|---|" + runs.joinToString("") { "---:|" } + "---:|:---:|")
        REPEATED.forEach { (key, label) ->
            val vals = runs.mapNotNull { it.num(key) }
            val s = spread(vals)
            appendLine("| $label | " + runs.joinToString(" | ") { f0(it.num(key)) } + " | ${s?.let { "%.1f%%".format(it * 100) } ?: "n/a"} | ${if (s == null) "n/a" else if (s <= TOLERANCE) "yes" else "**NO**"} |")
        }
        REPEATED_CPU.forEach { (key, label) ->
            val vals = runs.mapNotNull { it.num(key) }
            val d = if (vals.size < 2) null else vals.max() - vals.min()
            appendLine("| $label | " + runs.joinToString(" | ") { f2(it.num(key)) } + " | ${d?.let { "%.2f pt".format(it) } ?: "n/a"} | ${if (d == null) "n/a" else if (abs(d) <= CPU_ABS_TOLERANCE) "yes" else "**NO**"} |")
        }
        appendLine()
    }

    private fun StringBuilder.appendNmt(r: Run) {
        val cats = r.keys.filter { it.startsWith("daemon.load.nmt.") || it.startsWith("ui.load.nmt.") }.map { it.substringAfter(".nmt.") }.toSortedSet()
        if (cats.isEmpty()) return
        appendLine("## Where the memory goes (last run, after load, NMT committed MB)")
        appendLine()
        appendLine("NMT only sees memory the JVM itself allocates. Private bytes minus NMT total is a rough figure for native memory outside the JVM's books: on the UI that is mostly Skia/Direct3D/driver allocations; on both it includes the C runtime heap of native libraries (SQLite).")
        appendLine()
        appendLine("| Category | Daemon | UI |")
        appendLine("|---|---:|---:|")
        cats.sortedByDescending { (r.num("daemon.load.nmt.$it") ?: 0.0) + (r.num("ui.load.nmt.$it") ?: 0.0) }
            .filter { it == "Total" || (r.num("daemon.load.nmt.$it") ?: 0.0) + (r.num("ui.load.nmt.$it") ?: 0.0) >= 1.0 }
            .forEach { appendLine("| $it | ${f0(r.num("daemon.load.nmt.$it"))} | ${f0(r.num("ui.load.nmt.$it"))} |") }
        fun outside(who: String) = r.num("$who.load.privateMb")?.let { p -> r.num("$who.load.nmt.Total")?.let { p - it } }
        appendLine("| **Private bytes - NMT total (outside the JVM's books)** | ${f0(outside("daemon"))} | ${f0(outside("ui"))} |")
        appendLine()
    }

    private fun StringBuilder.appendReferenceApp(r: Run) {
        appendLine("## reference app at the same moments (NOT the same workload)")
        appendLine()
        appendLine("Read-only `Get-Process -Name ReferenceApp` (Electron) during the last run. reference app was running the owner's real agents, not the stub load above: this is context, not a like-for-like comparison.")
        appendLine()
        appendLine("| Moment | reference app WS total (MB) | Processes | Per process (MB) | Infantry daemon + UI WS (MB) |")
        appendLine("|---|---:|---:|---|---:|")
        listOf("idle" to "Infantry idle", "load" to "Infantry after load", "afterIdle" to "Infantry after idle", "afterGc" to "Infantry after full GC").forEach { (p, label) ->
            appendLine("| $label | ${f0(r.num("reference.$p.wsMb"))} | ${r["reference.$p.processes"] ?: "n/a"} | ${r["reference.$p.each"].orEmpty()} | ${f0(sum(r.num("daemon.$p.wsMb"), r.num("ui.$p.wsMb")))} |")
        }
        appendLine()
        appendLine("PM baseline 2026-10-20 (2 agents running in reference app): about 957 MB across 6 processes (571 + 246 + 109 + 19 + 9 + 3).")
        appendLine()
    }

    private fun StringBuilder.appendIsolation(runs: List<Run>) {
        appendLine("## Isolation (acceptance 3)")
        appendLine()
        runs.forEachIndexed { i, r ->
            appendLine("- Run ${i + 1}: owner untouched = **${r["guard.ownerUntouched"]}**${r["guard.violations"]?.takeIf { it.isNotBlank() }?.let { " ($it)" }.orEmpty()}. ${r["guard.ports"]}. ${r["guard.childHomes"]}. ${r["guard.stubs"]}.")
        }
        appendLine()
        appendLine("Asserted by `PerfGuard` (unit-tested in `PerfGuardTest`): requested and bound ports never 8787/8788; every temp dir under the run's temp root and never under `~/.infantry`; each child JVM's own `user.home` (read back with `jcmd VM.system_properties`) is the temp home; every stub agent's `INFANTRY_URL` names the temp daemon; and `~/.infantry/daemon.port` (content + mtime) and the pids listening on 8787/8788 are identical before and after. Inherited `INFANTRY_*` / `GIT_*` env is stripped from every child.")
        appendLine()
    }
}
